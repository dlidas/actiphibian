// Dependencies: flutter pub add sqflite path
import 'package:path/path.dart';
import 'package:sqflite/sqflite.dart';
import '../models/habit.dart';
import '../models/task.dart';
import '../models/user.dart';
import 'tables.dart';

class LocalDb {
  static Database? _database;

  static Future<Database> get database async {
    if (_database != null) return _database!;
    _database = await _initialiseDb();
    return _database!;
  }

  static Future<Database> _initialiseDb() async {
    return openDatabase(
      join(await getDatabasesPath(), 'actiphibian.db'),
      version: 2,
      onCreate: (db, version) async {
        await db.execute(Tables.users());
        await db.execute(Tables.habits());
        await db.execute(Tables.tasks());
        await db.execute(Tables.tags());
      },
      onUpgrade: (db, oldVersion, newVersion) async {
        if (oldVersion < 2) {
          await db.execute(Tables.habits());
          // Version 1's task table did not include these Task model fields.
          await db.execute(
            'ALTER TABLE tasks ADD COLUMN recurrenceFrequency TEXT',
          );
          await db.execute(
            'ALTER TABLE tasks ADD COLUMN perceivedDifficulty TEXT',
          );
        }
      },
    );
  }

  static Future<void> removeDatabase() async {
    final path = join(await getDatabasesPath(), 'actiphibian.db');
    await _database?.close();
    _database = null;
    await deleteDatabase(path);
  }

  static Future<void> addUser(User user) async {
    final db = await database;
    await db.insert(
      'users',
      user.toMap(),
      conflictAlgorithm: ConflictAlgorithm.fail,
    );
  }

  static Future<User?> getUser(int id) async {
    final db = await database;
    final users = await db.query('users', where: 'id = ?', whereArgs: [id]);
    if (users.isEmpty) return null;
    return User.fromMap(users.first);
  }

  static Future<List<User>> getUsers() async {
    final db = await database;
    final rows = await db.query('users');
    return rows.map(User.fromMap).toList();
  }

  static Future<void> updateUser(User user) async {
    final db = await database;
    await db.update(
      'users',
      user.toMap(),
      where: 'id = ?',
      whereArgs: [user.id],
    );
  }

  static Future<void> deleteUser(int id) async {
    final db = await database;
    await db.delete('users', where: 'id = ?', whereArgs: [id]);
  }

  /// Inserts a task and returns the ID generated by SQLite.
  static Future<int> addTask(Task task) async {
    final db = await database;
    final values = Map<String, Object?>.from(task.toMap())..remove('id');
    return db.insert(
      'tasks',
      values,
      conflictAlgorithm: ConflictAlgorithm.fail,
    );
  }

  static Future<Task?> getTask(int id) async {
    final db = await database;
    final rows = await db.query('tasks', where: 'id = ?', whereArgs: [id]);
    if (rows.isEmpty) return null;
    return Task.fromMap(rows.first);
  }

  static Future<List<Task>> getTasks() async {
    final db = await database;
    final rows = await db.query('tasks', orderBy: 'id ASC');
    return rows.map(Task.fromMap).toList();
  }

  static Future<void> updateTask(Task task) async {
    if (task.id == null) {
      throw ArgumentError('Cannot update a task without a database ID.');
    }
    final db = await database;
    final values = Map<String, Object?>.from(task.toMap())..remove('id');
    await db.update(
      'tasks',
      values,
      where: 'id = ?',
      whereArgs: [task.id],
    );
  }

  /// Saves completion and an optional recurring task atomically.
  /// Returns the inserted recurring task's ID, or null if there is no next task.
  static Future<int?> saveTaskCompletion(
    Task completedTask,
    Task? nextOccurrence,
  ) async {
    if (completedTask.id == null) {
      throw ArgumentError('Cannot complete a task without a database ID.');
    }
    final db = await database;
    return db.transaction<int?>((txn) async {
      final completedValues =
          Map<String, Object?>.from(completedTask.toMap())..remove('id');
      await txn.update(
        'tasks',
        completedValues,
        where: 'id = ?',
        whereArgs: [completedTask.id],
      );

      if (nextOccurrence == null) return null;
      final nextValues =
          Map<String, Object?>.from(nextOccurrence.toMap())..remove('id');
      return txn.insert(
        'tasks',
        nextValues,
        conflictAlgorithm: ConflictAlgorithm.fail,
      );
    });
  }

  static Future<void> deleteTask(int id) async {
    final db = await database;
    await db.delete('tasks', where: 'id = ?', whereArgs: [id]);
  }

  /// Inserts a habit and returns the SQLite ID. Passing an explicit ID is
  /// supported because the habit-creation dialog currently returns synchronously.
  static Future<int> addHabit(Habit habit) async {
    final db = await database;
    final values = Map<String, Object?>.from(habit.toMap());
    if (habit.id == null) values.remove('id');
    return db.insert(
      'habits',
      values,
      conflictAlgorithm: ConflictAlgorithm.fail,
    );
  }

  static Future<Habit?> getHabit(int id) async {
    final db = await database;
    final rows = await db.query('habits', where: 'id = ?', whereArgs: [id]);
    if (rows.isEmpty) return null;
    return Habit.fromMap(rows.first);
  }

  static Future<List<Habit>> getHabits() async {
    final db = await database;
    final rows = await db.query('habits', orderBy: 'id ASC');
    return rows.map(Habit.fromMap).toList();
  }

  static Future<void> updateHabit(Habit habit) async {
    if (habit.id == null) {
      throw ArgumentError('Cannot update a habit without a database ID.');
    }
    final db = await database;
    final values = Map<String, Object?>.from(habit.toMap())..remove('id');
    await db.update(
      'habits',
      values,
      where: 'id = ?',
      whereArgs: [habit.id],
    );
  }

  static Future<void> deleteHabit(int id) async {
    final db = await database;
    await db.delete('habits', where: 'id = ?', whereArgs: [id]);
  }
}
